// Real clarification/control SQL in isolated PostgreSQL. No production access.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
const { PGlite } = await import(pathToFileURL(process.env.OPRYN_PGLITE_MODULE));
const db = new PGlite();
const base = readFileSync("scripts/verify-gap-rechecks.mjs", "utf8").match(/await db\.exec\(`([\s\S]*?)`\);/)[1];
await db.exec(base);
await db.exec(`
create table profiles(id uuid primary key);
create function is_org_member(org uuid) returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.organization_members where organization_id=org and user_id=auth.uid())$$;
alter table employee_questions add column assigned_expert_id uuid,add column assigned_expert_rule_id uuid,add column status text default 'needs_owner',add column escalated boolean default true,add column resolved_at timestamptz;
alter table question_clusters add column classification text;
create table knowledge_events(organization_id uuid,event_type text,actor_id uuid,question_id uuid,metadata jsonb);
create table notifications(organization_id uuid,user_id uuid,type text,title text,body text,link text,entity_type text,entity_id uuid,action text,target_url text);
`);
await db.exec(readFileSync("supabase/migrations/20260916021000_gap_question_controls.sql", "utf8"));
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,"0")}`;
const [org,other,owner,expert,asker,stranger,foreign,question,cluster] = [1,2,3,4,5,6,7,8,9].map(id);
await db.query("insert into organizations values($1),($2)",[org,other]);
for(const person of [owner,expert,asker,stranger,foreign]) await db.query("insert into profiles values($1)",[person]);
await db.query("insert into organization_members values($1,$2,'owner',null),($1,$3,'member',null),($1,$4,'member',null),($1,$5,'member',null),($6,$7,'member',null)",[org,owner,expert,asker,stranger,other,foreign]);
await db.query("insert into question_clusters(id,organization_id) values($1,$2)",[cluster,org]);
await db.query("insert into employee_questions(id,organization_id,cluster_id,question,asked_by,assigned_expert_id) values($1,$2,$3,'Refund limit?',$4,$5)",[question,org,cluster,asker,expert]);
const actor = person => db.exec(`set role authenticated; set test.actor='${person}'`);
const control = (action,note="Which customer type?",target=null,clarification=null,workspace=org) => db.query("select manage_gap_question($1,$2,$3,$4,$5,$6) result",[workspace,question,action,target,note,clarification]);
await actor(stranger);
await assert.rejects(control("dismiss"),e=>e.code==="42501");
await actor(expert);
await assert.rejects(control("reroute","",asker),e=>e.code==="42501");
await assert.rejects(control("request_clarification",""),e=>e.code==="22023");
const clarification = (await control("request_clarification")).rows[0].result.clarificationId;
await assert.rejects(control("request_clarification"),e=>e.code==="40001");
await assert.rejects(control("reply","Enterprise customer",null,clarification),e=>e.code==="42501");
await actor(asker);
await assert.rejects(control("reply","Enterprise customer",null,id(999)),e=>e.code==="40001");
await control("reply","Enterprise customer",null,clarification);
await assert.rejects(control("reply","Enterprise customer",null,clarification),e=>e.code==="40001");
await actor(owner);
await assert.rejects(control("reroute","",foreign),e=>e.code==="22023");
await assert.rejects(control("reroute","",asker,null,other),e=>e.code==="42501");
await control("reroute","",asker);
await actor(expert);
await assert.rejects(control("dismiss"),e=>e.code==="42501");
await actor(asker);
await control("request_clarification","Which purchase date?");
await assert.rejects(control("dismiss",""),e=>e.code==="22023");
await control("dismiss","Not a company question");
await db.exec("reset role");
assert.equal((await db.query("select status from employee_questions")).rows[0].status,"dismissed");
assert.deepEqual((await db.query("select status from question_clarifications order by created_at")).rows.map(r=>r.status),["answered","canceled"]);
assert.equal((await db.query("select count(*)::int n from knowledge_proposals")).rows[0].n,0);
assert.equal((await db.query("select count(*)::int n from knowledge_chunks")).rows[0].n,0);
assert.equal((await db.query("select has_table_privilege('authenticated','question_clarifications','INSERT') allowed")).rows[0].allowed,false);
await db.close();
console.log("PASS: assigned-expert controls, admin-only tenant-safe rerouting, asker-only exact clarification replies, duplicate/stale protection, dismissal audit/cancellation; no policy publication.");
